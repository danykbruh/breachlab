## Три разных вещи

| | Можно вернуть исходный текст? | Нужен ключ? | Пример |
|---|---|---|---|
| **Кодирование** | Да, любой может | Нет | Base64, hex, URL-кодирование |
| **Шифрование** | Да, но только с ключом | Да | AES, RSA |
| **Хеширование** | Нет, это «отпечаток» | Нет | SHA-256, MD5 |

Частая ошибка: считать Base64 защитой. Base64 - это просто другой способ записать байты, его раскодирует кто угодно.

## Base64

Узнаётся по набору символов `A-Z a-z 0-9 + /` и знакам `=` в конце. Пример: `SGVsbG8=` → `Hello`.

## Hex (шестнадцатеричный вид)

Каждый байт - две цифры от `0` до `f`: `48 65 6c 6c 6f` → `Hello`.

## ROT13

Каждая латинская буква сдвигается на 13 позиций: `A↔N`, `B↔O`… Применить ROT13 дважды - получите исходный текст.

## Хеши

Хеш-функция из любых данных делает строку фиксированной длины. Одинаковый файл → одинаковый хеш, поэтому хеши используют для проверки целостности и как IOC.

- **MD5** - 32 hex-символа, устарел (найдены коллизии)
- **SHA-1** - 40 hex-символов, тоже устарел
- **SHA-256** - 64 hex-символа, современный стандарт

Все эти преобразования можно сделать на странице **«Инструменты»** в меню сверху.
