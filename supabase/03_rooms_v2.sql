-- Вспомогательная процедура: создать/обновить комнату одним вызовом
create or replace function public._upsert_room(p_slug text, p_title text, p_summary text, p_body text,
  p_category text, p_difficulty text, p_position integer, p_files jsonb default '[]')
returns bigint language plpgsql set search_path = '' as $$
declare rid bigint;
begin
  insert into public.rooms (slug, title, summary, body_md, category, difficulty, position, published, files)
  values (p_slug, p_title, p_summary, p_body, p_category, p_difficulty, p_position, true, p_files)
  on conflict (slug) do update set title = excluded.title, summary = excluded.summary, body_md = excluded.body_md,
    category = excluded.category, difficulty = excluded.difficulty, position = excluded.position,
    published = excluded.published, files = excluded.files
  returning id into rid;
  return rid;
end $$;
revoke all on function public._upsert_room(text, text, text, text, text, text, integer, jsonb) from public, anon, authenticated;

create or replace function public._upsert_task(p_slug text, p_position integer, p_question text, p_hint text, p_mask text, p_points integer)
returns void language sql set search_path = '' as $$
  insert into public.tasks (room_id, position, question, hint, answer_mask, points)
  select r.id, p_position, p_question, p_hint, p_mask, p_points from public.rooms r where r.slug = p_slug
  on conflict (room_id, position) do update set question = excluded.question, hint = excluded.hint,
    answer_mask = excluded.answer_mask, points = excluded.points;
$$;
revoke all on function public._upsert_task(text, integer, text, text, text, integer) from public, anon, authenticated;

