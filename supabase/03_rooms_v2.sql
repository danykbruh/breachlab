## Зачем защитнику Linux

Большинство серверов в мире работают на Linux. Аналитику нужно уметь пройтись по файлам, найти нужную строку в логе и понять, у кого какие права.

## Базовые команды

| Команда | Что делает |
|---|---|
| `pwd` | Показывает текущую папку |
| `ls -la` | Список файлов, включая скрытые |
| `cd /var/log` | Перейти в папку |
| `cat file.txt` | Вывести файл целиком |
| `less file.txt` | Листать большой файл |
| `grep "Failed" auth.log` | Найти строки с текстом |
| `grep -c "Failed" auth.log` | Посчитать такие строки |
| `tail -f syslog` | Следить за новыми строками в реальном времени |
| `find / -name "*.sh"` | Найти файлы по имени |
| `whoami` | Под каким пользователем я работаю |

## Важные места

- `/etc/passwd` - список пользователей системы
- `/etc/shadow` - хеши паролей (читать может только root)
- `/var/log/` - логи: `auth.log` (входы, sudo), `syslog` (система)
- `/tmp/` - временные файлы; злоумышленники любят класть туда свои скрипты

## Права на файлы

Строка `-rwxr-x---` делится на три группы по три символа: **владелец**, **группа**, **остальные**.

- `r` (read) = 4, `w` (write) = 2, `x` (execute) = 1
- `rwx` = 4+2+1 = **7**, `r-x` = 4+1 = **5**, `---` = **0**

Итого `rwxr-x---` = **750**. Команда `chmod 750 file` выставит такие права.

**root** - главный пользователь, которому можно всё. Команда `sudo` выполняет команду от имени root.
