## IP-адрес

**IP-адрес** - адрес устройства в сети, например `93.184.216.34`. Бывают **публичные** (видны из интернета) и **частные** (только внутри локальной сети).

Частные диапазоны IPv4:
- `10.0.0.0 - 10.255.255.255`
- `172.16.0.0 - 172.31.255.255`
- `192.168.0.0 - 192.168.255.255`

## Порты

На одном сервере работает много служб. **Порт** - номер, по которому понятно, к какой службе обращаются.

| Порт | Служба | Для чего |
|---|---|---|
| 21 | FTP | Передача файлов (без шифрования) |
| 22 | SSH | Удалённое управление сервером |
| 25 | SMTP | Отправка почты |
| 53 | DNS | Перевод доменных имён в IP |
| 80 | HTTP | Сайты без шифрования |
| 443 | HTTPS | Сайты с шифрованием |
| 3389 | RDP | Удалённый рабочий стол Windows |

## TCP и UDP

- **TCP** - надёжная доставка: перед передачей устанавливается соединение, потерянные пакеты отправляются заново.
- **UDP** - быстро и без гарантий: DNS-запросы, видеозвонки, игры.

## Рукопожатие TCP

Соединение TCP начинается с трёх шагов:

1. Клиент → сервер: **SYN** («хочу подключиться»)
2. Сервер → клиент: **SYN-ACK** («согласен»)
3. Клиент → сервер: **ACK** («подтверждаю»)

Сканеры портов (например, nmap) отправляют SYN на много портов и смотрят, где ответят SYN-ACK - там порт открыт.

## DNS

**DNS** переводит понятные имена (`example.com`) в IP-адреса. Без DNS пришлось бы запоминать цифры.
