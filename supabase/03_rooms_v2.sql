- `web-01` - имя сервера
- `sshd[31330]` - программа и номер процесса
- `Accepted password for deploy` - **успешный вход** пользователя `deploy` по паролю
- `from 203.0.113.45` - с какого IP

Другие важные строки:
- `Failed password for …` - неверный пароль
- `invalid user` - такого пользователя нет в системе
- `sudo: … COMMAND=` - команда, выполненная от root
- `useradd` - создание пользователя

## Как искать

**Linux / Git Bash:**
```
grep "Failed password" auth.log | grep -c "203.0.113.45"
grep "Accepted" auth.log
grep -E "sudo|useradd" auth.log
```

**Windows PowerShell:**
```
(Select-String -Path auth.log -Pattern "Failed password.*203.0.113.45").Count
Select-String -Path auth.log -Pattern "Accepted"
```

Можно и просто открыть файл в блокноте и воспользоваться поиском (`Ctrl+F`).

