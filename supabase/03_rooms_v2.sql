## Что такое SOC

**SOC (Security Operations Center)** - центр мониторинга безопасности. Это команда, которая круглосуточно следит за событиями в сети компании и реагирует на атаки.

## Линии аналитиков

| Линия | Чем занимается |
|---|---|
| **L1** | Первым разбирает оповещения (алерты): настоящая атака или ложное срабатывание? |
| **L2** | Глубоко расследует инциденты, которые передала L1 |
| **L3** | Эксперты: охота за угрозами (threat hunting), сложные расследования, правила детектирования |

## SIEM

**SIEM** (Security Information and Event Management) собирает логи со всех серверов, компьютеров и сетевых устройств в одно место и по правилам создаёт **алерты**. Примеры: Splunk, Elastic, MaxPatrol SIEM, KUMA.

## Как оценивают алерт

- **True Positive** - настоящая атака, алерт сработал правильно.
- **False Positive** - ложное срабатывание: алерт есть, а атаки нет.
- **False Negative** - самое опасное: атака была, а алерта нет.

## Индикаторы компрометации (IOC)

**IOC (Indicator of Compromise)** - следы атаки: IP-адреса злоумышленников, домены, хеши вредоносных файлов, подозрительные имена процессов.

