## SPF, DKIM, DMARC

- **SPF** - список серверов, которым домен разрешил отправлять почту. `spf=fail` - письмо пришло с чужого сервера.
- **DKIM** - цифровая подпись письма.
- **DMARC** - политика: что делать с письмами, которые не прошли проверки.

