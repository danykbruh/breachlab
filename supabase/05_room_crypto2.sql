## Когда простых кодировок мало

В этой комнате подсказок меньше, а задачи требуют думать. Все инструменты есть на странице **«Инструменты»**: XOR, перебор сдвигов Цезаря и SHA-256 для каждой строки списка.

## Слои

Данные часто кодируют несколько раз подряд. Снимайте слои по одному и каждый раз спрашивайте себя: *на что похож результат?* Base64, hex, ROT13 - узнавайте их по набору символов.

## XOR

XOR (исключающее «или») - основа многих шифров. Главное свойство:

```
текст  XOR ключ  = шифр
шифр   XOR ключ  = текст
шифр   XOR текст = ключ
```

Если ключ - один байт, а начало текста известно (например, все флаги начинаются с `BL{`), ключ находится за секунду: первый байт шифра XOR код символа `B` (`0x42`).

## Шифр Цезаря

Каждая буква сдвигается на одно и то же число позиций. Вариантов всего 25 - перебрать их все быстрее, чем гадать.

## Подбор хеша по словарю

Хеш нельзя «расшифровать», но можно посчитать хеш каждого слова из списка и сравнить. Именно поэтому слабые пароли из популярных словарей - плохая идея, а пароли в базах хранят с «солью».

> Все данные в комнате учебные. Словарь содержит только распространённые слова и нужен для демонстрации, почему такие пароли небезопасны.
