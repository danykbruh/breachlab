## Что такое OSINT

**OSINT** (Open Source Intelligence) — разведка по открытым источникам: сайты, соцсети, вакансии, новости, публичные документы. Защитники используют OSINT, чтобы увидеть свою компанию глазами злоумышленника и **убрать лишнее раньше, чем его найдут**.

## Что обычно «утекает» само

| Источник | Что можно узнать |
|---|---|
| Страница «Команда» | Имена, должности и **формат почты** — основа для фишинга |
| Вакансии | Какие системы и программы используются в компании |
| Фото из офиса | Стикеры с паролями, экраны, пропуска |
| Новости и пресс-релизы | Адреса офисов, партнёры, планы |

## Формат почты

Если на сайте есть хотя бы два адреса вида `имя.фамилия@компания`, почти наверняка так устроены адреса у всех сотрудников. Злоумышленнику этого достаточно, чтобы разослать фишинг по всему штату.

## Описание изображений

У картинок на сайтах бывает текстовое описание для незрячих (`alt` или `aria-label`). Его видно в коде страницы (`Ctrl+U`) — и иногда там написано больше, чем видно глазами.

