## Как ломают пароли

- **Перебор** — компьютер пробует все комбинации подряд.
- **Словарь** — проверяются популярные и утёкшие пароли (`qwerty`, `123456`, `password1`).
- **Credential stuffing** — пары «почта + пароль» из одной утечки пробуют на других сайтах. Работает, потому что люди повторяют пароли.

## Длина важнее сложности

Стойкость пароля измеряют в битах энтропии: `E = L × log₂(N)`, где `L` — длина, `N` — сколько разных символов может стоять на каждом месте.

| Набор символов | N | log₂(N) |
|---|---|---|
| Только цифры | 10 | ≈ 3,32 |
| Строчные латинские буквы | 26 | ≈ 4,70 |
| Строчные + заглавные + цифры | 62 | ≈ 5,95 |
| Все печатные символы | 95 | ≈ 6,57 |

Каждый добавленный символ умножает число вариантов, поэтому фраза из четырёх случайных слов обычно надёжнее короткого «P@ssw0rd».

## Как сайты должны хранить пароли

Никогда в открытом виде и не простым хешем. Правильно — медленными функциями с **солью**: **Argon2**, **bcrypt**, **scrypt**. Они специально сделаны медленными, чтобы перебор занимал годы.

## Двухфакторная аутентификация (2FA)

Второй фактор — то, что есть только у вас. От слабого к сильному:

1. **SMS-код** — лучше, чем ничего, но SIM-карту можно перевыпустить мошеннически.
2. **Приложение-аутентификатор (TOTP)** — код из 6 цифр, меняется каждые 30 секунд.
3. **Аппаратный ключ (FIDO2 / passkey)** — не даёт ввести данные на фишинговом сайте: ключ проверяет адрес сайта сам.

## Менеджер паролей

Один длинный мастер-пароль и уникальные случайные пароли для каждого сайта. Это самый практичный способ не повторять пароли.
