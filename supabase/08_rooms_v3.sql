## Зачем защитнику Windows

Большинство рабочих компьютеров в компаниях работают на Windows. Аналитик SOC должен понимать, где искать следы и как отличить нормальное поведение системы от подозрительного.

## Учётные записи и UAC

- **Администратор** может менять систему, **обычный пользователь** — нет. Работать каждый день под администратором опасно.
- **UAC** (контроль учётных записей) — окно «Разрешить этому приложению вносить изменения?». Оно появляется, когда программа просит права администратора.

## Процессы и службы

- **Процесс** — запущенная программа. Смотреть: **Диспетчер задач** (`Ctrl+Shift+Esc`).
- **Служба** — программа, которая работает в фоне без окна, часто запускается вместе с системой. Смотреть: `services.msc`.
- `svchost.exe` — системный процесс, который запускает службы. Настоящий лежит в `C:\Windows\System32`. Файл с таким же именем в другой папке — повод насторожиться.

## Автозагрузка

Вредоносные программы стараются закрепиться, чтобы запускаться после перезагрузки. Типичные места:

| Где | Что это |
|---|---|
| Папка «Автозагрузка» | Ярлыки программ, которые стартуют при входе пользователя |
| Ключи реестра `Run` | Например `HKCU\Software\Microsoft\Windows\CurrentVersion\Run` |
| Планировщик заданий | Задачи по расписанию или при входе в систему |
| Службы | Новая служба с автозапуском |

## Журналы событий

Программа **Просмотр событий** (`eventvwr.msc`) хранит журналы. Главные:

- **Безопасность** (Security) — входы в систему, изменения учётных записей;
- **Система** (System) — службы, драйверы, перезагрузки;
- **Приложение** (Application) — ошибки программ.

## PowerShell для осмотра системы

| Команда | Что делает |
|---|---|
| `Get-Process` | Список процессов |
| `Get-Service` | Список служб и их состояние |
| `Get-ScheduledTask` | Задания планировщика |
| `Get-LocalUser` | Локальные учётные записи |

