## Инцидент — это не паника, а процесс

Когда атака обнаружена, важно действовать по плану. Самая известная схема — **NIST SP 800-61**. Она делит реагирование на четыре этапа:

| № | Этап | Что делаем |
|---|---|---|
| 1 | **Подготовка** | Планы, контакты, резервные копии, обучение сотрудников — до инцидента |
| 2 | **Обнаружение и анализ** | Понять, что произошло, насколько серьёзно, какие системы затронуты |
| 3 | **Сдерживание, устранение, восстановление** | Изолировать заражённое, удалить причину, вернуть работу из чистых копий |
| 4 | **Действия после инцидента** | Разбор ошибок (lessons learned) и улучшения, чтобы не повторилось |

## Сдерживание — первым делом

Если компьютер заражён, его нужно **отключить от сети** (кабель, Wi-Fi), чтобы вирус не распространился дальше. При этом компьютер лучше **не выключать**: в оперативной памяти остаются следы, которые пригодятся для расследования.

## Шифровальщики

Шифровальщик (ransomware) шифрует файлы и требует выкуп. Главные правила:

- изолировать заражённые компьютеры;
- сообщить в SOC или ответственному за безопасность;
- **не платить выкуп** — нет гарантии, что файлы вернут, а злоумышленники получают деньги на новые атаки;
- восстанавливаться из **резервных копий**, которые хранятся отдельно (офлайн).

## Правило 3-2-1 для резервных копий

**3** копии данных, на **2** разных типах носителей, **1** из них — вне офиса или офлайн.

